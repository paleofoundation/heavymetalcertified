#!/usr/bin/env node
// Validate the three-door editorial seed and emit the typed module TopNav uses.
// Every route is checked against content/ before output is written. Density is
// also a build invariant: three panels, three groups per panel, at most six
// links per group, and at most sixteen links per panel.

import fs from "node:fs"
import path from "node:path"
import { pathToFileURL } from "node:url"

const repoRoot = process.cwd()
const contentRoot = path.join(repoRoot, "content")
const seedPath = path.join(repoRoot, "quartz/components/navPanels.seed.ts")
const outPath = path.join(repoRoot, "quartz/components/generated/navPanels.ts")
const dryRun = process.argv.slice(2).includes("--dry-run")

const seedSource = fs.readFileSync(seedPath, "utf8")
const stripped = seedSource
  .replace(/^export interface[\s\S]*?^\}/gm, "")
  .replace(/^\s*\/\/.*$/gm, "")
  .replace(/export const seedPanels: SeedPanel\[\] =/, "export const seedPanels =")
const tmpPath = path.join(repoRoot, "node_modules/.cache/hmtc-nav-seed.mjs")
fs.mkdirSync(path.dirname(tmpPath), { recursive: true })
fs.writeFileSync(tmpPath, stripped, "utf8")
const { seedPanels } = await import(`${pathToFileURL(tmpPath).href}?v=${fs.statSync(seedPath).mtimeMs}`)

function slugExists(slug) {
  return (
    fs.existsSync(path.join(contentRoot, `${slug}.md`)) ||
    fs.existsSync(path.join(contentRoot, slug, "index.md"))
  )
}

const failures = []
if (seedPanels.length !== 3) failures.push(`expected exactly 3 panels; found ${seedPanels.length}`)

for (const panel of seedPanels) {
  if (!slugExists(panel.slug)) failures.push(`${panel.key}: hub route '${panel.slug}' does not exist`)
  if (panel.groups.length !== 3) {
    failures.push(`${panel.key}: expected exactly 3 groups; found ${panel.groups.length}`)
  }

  const seen = new Set()
  let total = 0
  for (const group of panel.groups) {
    if (group.children.length < 1 || group.children.length > 6) {
      failures.push(
        `${panel.key} › ${group.heading}: expected 1–6 links; found ${group.children.length}`,
      )
    }
    total += group.children.length
    for (const child of group.children) {
      if (!slugExists(child.slug)) {
        failures.push(`${panel.key} › ${group.heading}: route '${child.slug}' does not exist`)
      }
      const destination = `${child.slug}${child.anchor ? `#${child.anchor}` : ""}`
      if (seen.has(destination)) {
        failures.push(`${panel.key}: duplicate destination '${destination}'`)
      }
      seen.add(destination)
    }
  }
  if (total > 16) failures.push(`${panel.key}: expected at most 16 links; found ${total}`)
}

if (failures.length) {
  console.error("build-nav-panels: FAIL")
  for (const failure of failures) console.error(`  ${failure}`)
  process.exit(1)
}

const panels = seedPanels.map((panel) => ({
  key: panel.key,
  label: panel.label,
  panelLabel: panel.panelLabel ?? panel.label,
  slug: panel.slug,
  blurb: panel.blurb,
  extraPrefixes: panel.extraPrefixes,
  groups: panel.groups,
  allLabel: panel.allLabel,
}))

const module = `// GENERATED by tools/build-nav-panels.mjs — do not edit.
// Editorial source: quartz/components/navPanels.seed.ts

export interface NavChild {
  label: string
  slug: string
  anchor?: string
}

export interface NavGroup {
  heading: string
  children: NavChild[]
}

export interface NavPanel {
  key: string
  label: string
  panelLabel: string
  slug: string
  blurb: string
  extraPrefixes: string[]
  groups: NavGroup[]
  allLabel: string
}

export const navPanels: NavPanel[] = ${JSON.stringify(panels, null, 2)}
`

const previous = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : ""
const linkCount = panels.reduce(
  (sum, panel) => sum + panel.groups.reduce((groupSum, group) => groupSum + group.children.length, 0),
  0,
)

if (previous === module) {
  console.log(`build-nav-panels: unchanged (3 panels, ${linkCount} curated links).`)
} else if (dryRun) {
  console.log(`build-nav-panels: DRY-RUN would update ${path.relative(repoRoot, outPath)}.`)
} else {
  fs.mkdirSync(path.dirname(outPath), { recursive: true })
  fs.writeFileSync(outPath, module, "utf8")
  console.log(`build-nav-panels: wrote 3 panels, ${linkCount} curated links.`)
}

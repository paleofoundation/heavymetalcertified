#!/usr/bin/env node
// Render the Infant & Child Foods (Category 1) Program Manual landing page in the canonical v3
// design. This is the citable web edition: it presents the complete 9-subcategory standard set as
// one master matrix and links each subcategory to its full derivation page. Numbers come from
// tools/lib/cat1-manual-data.mjs (which reads data/standards/cat1-compiled/<record>.json +
// data/standards/cat1-pages.json deterministically; no authored values).
//
// The PAGE STRUCTURE is produced by the SHARED tools/lib/manual-page.mjs renderer — the single
// source every Program Manual uses, so cat1 and the config-driven categories are byte-identical in
// design. This generator only assembles cat1's DATA (matrix, snapshot, method note, connections)
// and hands it to renderManualPage(). See [[project_manual_v3_canonical_design]].
//
// Not manifest-managed (kept out of manifest.json so build-manuals-page.mjs does not overwrite it).
//
// The consolidated PDF: the current v2 (9-subcategory, Method v2.0) manual PDF is generated by
// tools/build-cat1-manual-pdf.mjs into content/static/manuals/ and committed there, built from the
// SAME lib as this page so the two can never diverge. When present this page offers it (rail PdfCard
// + hero link); when absent it degrades to "in preparation" rather than a dead link.

import fs from "node:fs"
import path from "node:path"
import { masterMatrix, ANALYTES } from "./lib/cat1-manual-data.mjs"
import { renderStruggleSection } from "./lib/struggle-section.mjs"
import { renderManualPage } from "./lib/manual-page.mjs"

const REPO = process.cwd()
const OUT = path.join(REPO, "content/manuals/infant-and-child-foods.md")
const OCC = JSON.parse(fs.readFileSync(path.join(REPO, "data/standards/occurrence-evidence.json"), "utf8"))
const LINK = "#1c43ad", ACCENT = "#9f2727"

// The served consolidated PDF (v2). Generated by build-cat1-manual-pdf.mjs, committed under /static.
const PDF_FILE = "HMTc-Infant-and-Child-Foods-Program-Manual-2026-v2.pdf"
const PDF_HREF = `/static/manuals/${PDF_FILE}`
const pdfServed = fs.existsSync(path.join(REPO, "content/static/manuals", PDF_FILE))

const rows = masterMatrix()
const sym = (key) => (key === "tHg" ? "Hg" : key)
const tier1Labels = ANALYTES.filter((a) => a.tier === "Tier 1").map((a) => sym(a.key))
const tier2Labels = ANALYTES.filter((a) => a.tier === "Tier 2").map((a) => sym(a.key))

const struggleHtml = renderStruggleSection({
  compiledDir: path.join(REPO, "data/standards/cat1-compiled"),
  occurrence: OCC,
  categoryDirName: "cat1-compiled",
  categoryName: "Infant and Child Foods",
  LINK,
  ACCENT,
})

const editionPdfLine = pdfServed
  ? "The consolidated, version-pinned PDF of the full expanded manual is available in the rail and links every value to its derivation; each subcategory page remains individually downloadable and citable."
  : "A consolidated, version-pinned PDF of the full expanded manual is in preparation and will be linked here on release; until then each subcategory page is individually downloadable and citable."

const railBody = pdfServed
  ? "Web edition current — nine subcategories, 2026-08-06 (Method v2.0). The consolidated, version-pinned PDF is downloadable here; a DOI is minted on deposit. The earlier 384-page deposited editions stay citable on Zenodo. Full edition history below."
  : "Web edition current — nine subcategories, 2026-08-06 (Method v2.0). A consolidated, version-pinned PDF is in preparation and a DOI is minted on deposit; the earlier 384-page deposited editions stay citable on Zenodo. Full edition history below."

const methodNoteHtml =
  `The 8:1 powder-to-liquid basis conversion applies only within infant formula; every other subcategory takes government limits at face value. Tier&nbsp;1 toxics (Pb, Cd, iAs, Hg) are zero-tolerance; Tier&nbsp;2 (tAs, Ni, Al, Sn, Cr) carry the program&rsquo;s 150% transitional allowance. <a href="/analytes/arsenic" style="color:${LINK}">Arsenic</a> is limited in both forms &mdash; total arsenic (tAs) and inorganic arsenic (iAs) are separate ceilings that must both be met, and the species result never replaces the parent total. Where an analyte is not regulated for a product and is not material in that matrix, it is controlled &mdash; total-<a href="/analytes/chromium" style="color:${LINK}">chromium</a> screening with reflex hexavalent-chromium speciation, any quantifiable Cr(VI) a hard fail &mdash; rather than assigned an invented number.`

const page = renderManualPage({
  title: "Infant and Child Foods — HMTc Program Manual",
  category: 1,
  manualSlug: "infant-and-child-foods",
  categoryName: "Infant and Child Foods",
  description:
    "The complete Heavy Metal Tested & Certified standard for Category 1, Infant and Child Foods (ages 0–5), edition 2026.",
  snapshot: [
    { k: "Subcategories", v: String(rows.length) },
    { k: "Analyte panel", v: `${ANALYTES.length} analytes` },
    { k: "Method", v: "Strictest government ML" },
    { k: "Web edition", v: "2026-08-06" },
  ],
  connections: [
    { label: "The standards register", href: "/standards" },
    { label: "How limits are derived", href: "/program/structure" },
    { label: "Verify a certificate", href: "/verify" },
    { label: "All Program Manuals", href: "/manuals" },
    { label: "Heavy Metal Index — literature baseline", href: "https://heavymetalindex.com" },
  ],
  pdfHref: pdfServed ? PDF_HREF : null,
  pdfLabel: "Download PDF · 2026 v2",
  railBody,
  effectiveDate: "2026",
  updated: "2026-08-06",
  methodNoteHtml,
  matrix: {
    analytes: ANALYTES.map((a) => ({ key: a.key, col: a.col })),
    rows,
    tier1Labels,
    tier2Labels,
    note: `All values ppb (&micro;g/kg) in each row&rsquo;s native basis. Split cells show the formulation or matrix variants (cow/soy, rice/non-rice). Click any subcategory for its full government-by-government derivation. n/m = not material in the matrix: measured but with no standalone number, controlled by the total-metal screen or packaging control, not an invented value.`,
  },
  struggleHtml,
  editionPdfLine,
})

fs.writeFileSync(OUT, page)
console.log(`build-cat1-manual: wrote ${path.relative(REPO, OUT)} (${rows.length} subcategories, pdf ${pdfServed ? "served" : "pending"})`)

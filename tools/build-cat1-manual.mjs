#!/usr/bin/env node
// Render the Infant & Child Foods (Category 1) manual landing page from the compiled records +
// page metadata. This is the citable web edition: it presents the complete 9-subcategory standard
// set as one master matrix and links each subcategory to its full derivation page. Numbers come
// from tools/lib/cat1-manual-data.mjs (which reads data/standards/cat1-compiled/<record>.json +
// data/standards/cat1-pages.json deterministically; no authored values).
//
// Not manifest-managed (kept out of manifest.json so build-manuals-page.mjs does not overwrite it).
//
// The consolidated PDF: the current v2 (9-subcategory, Method v2.0) manual PDF is generated by
// tools/build-cat1-manual-pdf.mjs into content/static/manuals/ and committed there. It is built
// from the SAME lib as this page, so the two can never diverge. When that file is present this page
// renders a working Download-PDF affordance; when it is absent it degrades to "in preparation" text
// rather than a dead link. The old single-subcategory 384-page deposited PDF (Zenodo) is NEVER
// served against this 9-subcategory edition — shipping a stale standard would be a Daubert self-harm.

import fs from "node:fs"
import path from "node:path"
import { masterMatrix, ANALYTES } from "./lib/cat1-manual-data.mjs"

const REPO = process.cwd()
const OUT = path.join(REPO, "content/manuals/infant-and-child-foods.md")

// The served consolidated PDF (v2). Generated by build-cat1-manual-pdf.mjs, committed under /static.
const PDF_FILE = "HMTc-Infant-and-Child-Foods-Program-Manual-2026-v2.pdf"
const PDF_HREF = `/static/manuals/${PDF_FILE}`
const pdfServed = fs.existsSync(path.join(REPO, "content/static/manuals", PDF_FILE))

const ACCENT = "#9f2727", LINK = "#1c43ad"

const th = (t) => `<th style="text-align:${t.a || "right"};padding:9px 10px;font-family:'IBM Plex Mono',monospace;font-size:9.5px;font-weight:500;letter-spacing:.06em">${t.t}</th>`

// The nine subcategory rows + eight display values each, from the shared lib — the same arrays the
// PDF renders, so the download can never drift from this table.
const rows = masterMatrix()
let bodyRows = ""
for (const row of rows) {
  const href = `/standards/${row.slug}`
  const tds = ANALYTES.map((a) => `<td style="padding:9px 10px;text-align:right;font-family:'IBM Plex Mono',monospace;color:#2b1f1f">${row.cells[a.key]}</td>`).join("")
  bodyRows += `<tr style="border-bottom:1px solid #f2ece7"><td style="padding:9px 12px"><a href="${href}" style="color:${LINK};text-decoration:none">${row.name}</a></td>${tds}<td style="padding:9px 10px;font-size:11px;color:#a9a1a1">${row.basis}</td></tr>\n`
}

const matrix = `<div style="overflow-x:auto"><table style="width:100%;font-size:12.5px;border:1px solid #e8e1db;min-width:56rem;border-collapse:collapse"><thead><tr style="background:${ACCENT};color:#fff">${th({ t: "Subcategory", a: "left" })}${ANALYTES.map((a) => th({ t: a.col })).join("")}${th({ t: "Basis", a: "left" })}</tr></thead><tbody>\n${bodyRows}</tbody></table></div>`

// Working Download-PDF affordance (mirrors the briefing/standard download button), rendered only
// when the served PDF is actually present, so the page never links a file that is not there.
const downloadBlock = pdfServed
  ? `<div style="margin:0 0 6px"><a href="${PDF_HREF}" download style="display:inline-block;background:${ACCENT};color:#fff;font-family:'IBM Plex Mono',monospace;font-size:12.5px;letter-spacing:.02em;text-decoration:none;padding:11px 18px;border-radius:4px">&#8595; Download the full Program Manual (PDF, 2026 v2)</a> <span style="font-size:11.5px;color:#a9a1a1">The complete five-part manual — governance and certification-status framework, the standards with their full derivations, and the lot-testing schedule — version-pinned and self-contained.</span></div>`
  : `<p style="font-size:12.5px;color:#a9a1a1;margin:0">A consolidated, version-pinned PDF of the full expanded manual is in preparation and will be linked here on release.</p>`

const editionPdfLine = pdfServed
  ? `The consolidated, version-pinned PDF of the full expanded manual is available above and links every value to its derivation; each subcategory page remains individually downloadable and citable.`
  : `A consolidated, version-pinned PDF of the full expanded manual is in preparation and will be linked here on release; until then each subcategory page is individually downloadable and citable.`

const railBody = pdfServed
  ? "Web edition current — nine subcategories, 2026-08-06 (Method v2.0). The consolidated, version-pinned PDF is downloadable here; a DOI is minted on deposit. The earlier 384-page deposited editions stay citable on Zenodo. Full edition history below."
  : "Web edition current — nine subcategories, 2026-08-06 (Method v2.0). A consolidated, version-pinned PDF is in preparation and a DOI is minted on deposit; the earlier 384-page deposited editions stay citable on Zenodo. Full edition history below."

const fm = [
  "---",
  'title: "Infant and Child Foods — HMTc Program Manual"',
  "type: standard",
  "custom_page: true",
  "category: 1",
  "scholar_eligible: true",
  "cert_doi: null",  // the current 9-subcategory WEB edition has no DOI yet (Crossref go-forward; deposit pending). The DOI'd artifact is a SEPARATE, superseded 384-page ~15-subcategory deposited volume — concept DOI 10.5281/zenodo.20270511 → v0 20270512 (2026-05-18), latest 20771543 (2026-06-20). Full lineage: data/standards/version-history/infant-and-child-foods.json (rail_box + version-history table below are generated from it).
  "effective_date: 2026",
  "audience: [regulator, brand-legal, retailer-compliance, certifier]",
  "rail_box:",
  '  title: "Document versions"',
  `  body: "${railBody}"`,
  ...(pdfServed ? ['  cta_label: "Download PDF (2026 v2)"', `  cta_href: "${PDF_HREF}"`] : []),
  "---",
].join("\n")

const body = `
<section style="margin-bottom:44px"><h1 style="font-family:Lora,serif;font-weight:400;font-size:34px;line-height:1.15;color:#2b1f1f;margin:0 0 14px">Infant and Child Foods — HMTc Program Manual</h1>
<p style="font-size:16px;line-height:1.7;color:#3f3a3a;max-width:80ch;margin:0 0 14px">The complete Heavy Metal Tested &amp; Certified standard for Category&nbsp;1, Infant and Child Foods (ages 0–5), edition 2026. Each initial limit is the strictest maximum level set by a credible sovereign government, converted to the product&rsquo;s native basis, with disclosed regulatory read-across where the exact cell is unregulated. After publication, a later edition may be lower only through the <a href="/program/ratchet" style="color:${LINK};text-decoration:none">Standards Ratchet</a> using eligible HMTc certified-lot results.</p>
<p style="font-size:13.5px;line-height:1.7;color:#736b6b;max-width:80ch;margin:0 0 18px">Method: <a href="/program/structure" style="color:${LINK};text-decoration:none">government-limit-only (Method v2.0)</a>. The 8:1 powder-to-liquid basis conversion applies only within infant formula; every other subcategory takes government limits at face value. Tier&nbsp;1 toxics (Pb, Cd, iAs, Hg) are zero-tolerance; Tier&nbsp;2 (Ni, Al, Sn, Cr) carry the program&rsquo;s 150% transitional allowance. Where an analyte is not regulated for a product and is not material in that matrix, it is controlled — total-chromium screening with reflex hexavalent-chromium speciation, any quantifiable Cr(VI) a hard fail — rather than assigned an invented number.</p>
${downloadBlock}</section>

<section style="margin-bottom:44px"><h2 style="font-family:Lora,serif;font-weight:400;font-size:28px;color:#2b1f1f;border-bottom:1px solid #e8e1db;padding-bottom:10px;margin:0 0 18px">Master limit matrix — all nine subcategories</h2>
<p style="font-size:11.5px;color:#a9a1a1;margin:0 0 12px">All values ppb (µg/kg) in each row&rsquo;s native basis. Split cells show the formulation or matrix variants (cow/soy, rice/non-rice). Click any subcategory for its full government-by-government derivation. <span style="font-weight:500">n/m</span> = not material in the matrix; controlled by reflex speciation, not a number.</p>
${matrix}</section>

<section style="margin-bottom:20px"><h2 style="font-family:Lora,serif;font-weight:400;font-size:28px;color:#2b1f1f;border-bottom:1px solid #e8e1db;padding-bottom:10px;margin:0 0 18px">About this edition</h2>
<p style="font-size:13.5px;line-height:1.7;color:#736b6b;max-width:80ch;margin:0 0 12px">Standards are living, versioned documents; each subcategory page carries its own version history and dated change log. This is the current web edition. ${editionPdfLine}</p>
<p style="font-size:12.5px;line-height:1.65;color:#a9a1a1;max-width:80ch;margin:0">Descriptive occurrence evidence is maintained independently at the <a href="https://heavymetalindex.com" style="color:${LINK}">Heavy Metal Index</a>. It provides context only and does not select an initial limit or certification status; initial limits come from the government-limit-only compiler and later tightening may use only eligible HMTc certified-lot data under the Standards Ratchet.</p></section>
`

fs.writeFileSync(OUT, fm + "\n" + body)
console.log(`build-cat1-manual: wrote ${path.relative(REPO, OUT)} (${rows.length} subcategories, pdf ${pdfServed ? "served" : "pending"})`)

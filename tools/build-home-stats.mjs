#!/usr/bin/env node
// build-home-stats.mjs — refresh homepage "Program at a glance" from the live SoT.
//
// Writes:
//   data/home-stats.json                      checked-in artifact
//   quartz/components/generated/home-stats.ts consumed by HomeHero
//   reports/HOME-STATS-SCORECARD.md           metric definitions + counts
//   content/index.md frontmatter              snapshot rows; kills frozen dates
//
// Wired into prebuild so Quartz always sees a refreshed snapshot. Does not mint
// DataCite. Does not invent ppb.
//
// Usage: node tools/build-home-stats.mjs [--quiet]

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { assertHomeStats, computeHomeStats } from "./lib/home-stats.mjs"

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const QUIET = process.argv.includes("--quiet")

const stats = computeHomeStats({
  contentDir: path.join(REPO, "content/standards"),
  dataDir: path.join(REPO, "data/standards"),
  manualsPath: path.join(REPO, "data/manuals/manifest.json"),
})
assertHomeStats(stats)

const jsonPath = path.join(REPO, "data/home-stats.json")
const tsPath = path.join(REPO, "quartz/components/generated/home-stats.ts")
const scorecardPath = path.join(REPO, "reports/HOME-STATS-SCORECARD.md")
const indexPath = path.join(REPO, "content/index.md")

const payload = {
  _doc: "GENERATED by tools/build-home-stats.mjs — do not hand-edit. Homepage snapshot source of truth.",
  ...stats,
}

fs.mkdirSync(path.dirname(jsonPath), { recursive: true })
fs.writeFileSync(jsonPath, JSON.stringify(payload, null, 2) + "\n")

fs.mkdirSync(path.dirname(tsPath), { recursive: true })
fs.writeFileSync(
  tsPath,
  `// GENERATED by tools/build-home-stats.mjs — do not hand-edit.\n` +
    `export const homeStats = ${JSON.stringify(payload, null, 2)} as const\n`,
)

const m = stats.metrics
const scorecard = `# SCORECARD — HMTC-HOME-GLANCE-THIN-1

Generated by \`tools/build-home-stats.mjs\`. Claim-surface evaluation is
\`tools/lib/claim-surface.mjs\`. Do not invent ppb. Do not mint DataCite from
this file. Counts are live-at-build (\`as_of\` ${stats.as_of || "omit"}).

**Glance = 3 rows only.** Homepage snapshot is Subcategory standards in force,
Live DOIs, Priority metals. Cut metrics stay in this table for tests; they do
not appear in \`snapshot_rows\` or HomeHero.

## Metrics

| Metric | Count | Definition |
|---|---:|---|
| subcategory_standards_in_force | ${m.subcategory_standards_in_force} | ${stats.definitions.subcategory_standards_in_force} |
| carrying_firm_limit | ${m.carrying_firm_limit} | ${stats.definitions.carrying_firm_limit} |
| firm_analyte_limits | ${m.firm_analyte_limits} | ${stats.definitions.firm_analyte_limits} |
| certified_analyte_panel | ${m.certified_analyte_panel} | ${stats.definitions.certified_analyte_panel} |
| priority_metals | ${m.priority_metals} | ${stats.definitions.priority_metals} |
| current_edition | ${m.current_edition} | ${stats.definitions.current_edition} |
| live_dois | ${m.live_dois} | ${stats.definitions.live_dois} |
| as_of | ${stats.as_of || "(omitted on homepage)"} | ${stats.definitions.as_of} |

## Exclusions

- chocolate carrying_firm_limit: \`${stats.exclusions.chocolate_carrying_firm_limit}\` (must be false or null — incomplete claim surface is not COMPLETE)

## Snapshot rows (homepage)

Glance = 3 rows only.

${stats.snapshot_rows.map(([k, v]) => `- ${k}: \`${v}\``).join("\n")}
`

fs.mkdirSync(path.dirname(scorecardPath), { recursive: true })
fs.writeFileSync(scorecardPath, scorecard)

function patchHomepage(raw, snapshot) {
  let out = raw.replace(/^home_snapshot_date:.*\n/m, "")
  out = out.replace(/^home_snapshot:\n(?:[ \t]*- .+\n)+/m, "")
  const rows = snapshot.map(([k, v]) => `  - [${JSON.stringify(k)}, ${JSON.stringify(v)}]`).join("\n")
  const close = out.indexOf("\n---", 4)
  if (close < 0) throw new Error("home-stats: content/index.md is missing a frontmatter close")
  out = `${out.slice(0, close)}\nhome_snapshot:\n${rows}${out.slice(close)}`
  if (/22 August 2026|August 22, 2026/i.test(out)) {
    throw new Error("home-stats: frozen August snapshot still present in content/index.md")
  }
  if (/Today 348 subcategory|ten-analyte panel/i.test(out)) {
    throw new Error("home-stats: stale homepage marketing counts still in content/index.md")
  }
  return out
}

if (fs.existsSync(indexPath)) {
  const next = patchHomepage(fs.readFileSync(indexPath, "utf8"), stats.snapshot_rows)
  fs.writeFileSync(indexPath, next)
}

if (!QUIET) {
  console.log(
    `home-stats: ${m.subcategory_standards_in_force} in force | ${m.carrying_firm_limit} COMPLETE | ${m.firm_analyte_limits} firm cells | panel ${m.certified_analyte_panel} | ${m.live_dois} live DOIs | edition ${m.current_edition}`,
  )
  console.log(`  wrote ${path.relative(REPO, jsonPath)}`)
  console.log(`  wrote ${path.relative(REPO, tsPath)}`)
  console.log(`  wrote ${path.relative(REPO, scorecardPath)}`)
  console.log(`  patched content/index.md snapshot`)
}
